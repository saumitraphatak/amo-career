#!/usr/bin/env node
/* Builds js/search-sections.js: every page's section headings for the site
   search (main.js initGlobalSearch → "Sections" results).

     node tests/browser/build-section-index.js [siteRoot]

   Loads each pages/*.html in Playwright (Chart.js stubbed, nothing fetched
   from the network), lets main.js build chapters, and records
   AMOSections.collect(): heading text, its #s-<slug> address and the
   chapter it sits in. Run it after adding, renaming or removing sections,
   then bump the ?v= in initGlobalSearch's loadSections(). */
const { chromium } = require('playwright');
const http = require('http'), fs = require('fs'), path = require('path');

const dir = path.resolve(process.argv[2] || path.join(__dirname, '..', '..'));
const STUB = path.join(__dirname, 'chartstub.js');
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.json': 'application/json' };

const srv = http.createServer((q, r) => {
  const p = path.join(dir, decodeURIComponent(q.url.split('?')[0].split('#')[0]));
  if (!p.startsWith(dir)) { r.writeHead(403); return r.end(); }
  fs.readFile(p, (e, b) => { if (e) { r.writeHead(404); return r.end(); } r.writeHead(200, { 'Content-Type': TYPES[path.extname(p)] || 'application/octet-stream' }); r.end(b); });
}).listen(0, '127.0.0.1', async () => {
  const port = srv.address().port;
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  await ctx.route('**/*', r => r.request().url().startsWith(`http://127.0.0.1:${port}`) ? r.continue() : r.abort());
  await ctx.addInitScript({ path: STUB });
  const pages = fs.readdirSync(path.join(dir, 'pages')).filter(f => f.endsWith('.html')).sort();
  const out = [];
  for (const f of pages) {
    const page = await ctx.newPage();
    await page.goto(`http://127.0.0.1:${port}/pages/${f}`, { waitUntil: 'load' });
    await page.waitForTimeout(300);
    const secs = await page.evaluate(() => window.AMOSections ? AMOSections.collect() : []);
    const key = f.replace(/\.html$/, '');
    secs.forEach(s => out.push({ p: key, t: s.t, s: s.s, ...(s.c ? { c: s.c } : {}) }));
    console.log(`${key}: ${secs.length}`);
    await page.close();
  }
  await browser.close(); srv.close();
  const body = '/* Generated by tests/browser/build-section-index.js — do not edit by hand.\n' +
    '   Section headings for the site search: p = page, t = heading, s = #s-<slug> anchor, c = chapter. */\n' +
    'window.AMO_SECTION_INDEX = [\n' + out.map(o => '  ' + JSON.stringify(o)).join(',\n') + '\n];\n';
  fs.writeFileSync(path.join(dir, 'js', 'search-sections.js'), body);
  console.log(`wrote js/search-sections.js: ${out.length} sections, ${(body.length / 1024).toFixed(1)} KB`);
});
